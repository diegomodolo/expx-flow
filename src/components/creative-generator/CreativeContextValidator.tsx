import React, { useEffect, useState } from "react";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Textarea } from "@/components/ui/textarea";
import { Label } from "@/components/ui/label";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { CheckCircle, FileText, Target, Users, MessageSquare, Quote, Sparkles, Loader2 } from "lucide-react";
import { supabase } from "@/integrations/supabase/client";
import { useClients } from "@/hooks/useClients";
import { toast } from "@/hooks/use-toast";

interface CreativeContext {
  title: string;
  description: string;
  objective: string;
  targetAudience: string;
  copy: string;
  caption: string;
}

interface CreativeContextValidatorProps {
  context: CreativeContext;
  onContextUpdate: <K extends keyof CreativeContext>(key: K, value: CreativeContext[K]) => void;
  theme: string;
  clientId: string;
  creativeType: string;
}

export function CreativeContextValidator({ 
  context, 
  onContextUpdate, 
  theme, 
  clientId, 
  creativeType 
}: CreativeContextValidatorProps) {
  const [isGenerating, setIsGenerating] = useState(false);
  const [hasAutoGenerated, setHasAutoGenerated] = useState(false);
  const { clients } = useClients();
  
  const client = clients?.find(c => c.id === clientId);
  
  const completedFields = Object.values(context).filter(value => value.trim() !== "").length;
  const totalFields = Object.keys(context).length;
  const completionPercentage = Math.round((completedFields / totalFields) * 100);
  const hasEmptyFields = completedFields === 0;

  const generateContextWithAI = async () => {
    console.log('Debug - generateContextWithAI called:', { theme, clientId, client });
    
    if (!theme || !clientId) {
      toast({
        title: "Erro",
        description: `Dados incompletos: tema="${theme}", clientId="${clientId}"`,
        variant: "destructive",
      });
      return;
    }

    if (!client) {
      toast({
        title: "Erro", 
        description: `Cliente não encontrado para ID: ${clientId}`,
        variant: "destructive",
      });
      return;
    }

    setIsGenerating(true);
    try {
      console.log('Calling generate-creative-context with data:', {
        theme,
        creativeType,
        clientBriefing: client.ai_briefing || '',
        clientSector: client.sector || '',
        targetAudience: client.notes || '',
        voiceTone: client.voice_tone || ''
      });

      const { data, error } = await supabase.functions.invoke('generate-creative-context', {
        body: {
          theme,
          creativeType,
          clientBriefing: client.ai_briefing || '',
          clientSector: client.sector || '',
          targetAudience: client.notes || '',
          voiceTone: client.voice_tone || ''
        }
      });

      console.log('Edge function response:', { data, error });

      if (error) throw error;

      if (data?.context) {
        // Atualizar todos os campos do contexto
        Object.entries(data.context).forEach(([key, value]) => {
          onContextUpdate(key as keyof CreativeContext, value as string);
        });
        
        toast({
          title: "Contexto gerado com sucesso!",
          description: "Os campos foram preenchidos automaticamente com base no tema escolhido.",
        });
      }
    } catch (error: any) {
      console.error('Error generating context:', error);
      toast({
        title: "Erro ao gerar contexto",
        description: "Não foi possível gerar o contexto automaticamente. Preencha manualmente.",
        variant: "destructive",
      });
    } finally {
      setIsGenerating(false);
    }
  };

  // Auto-gerar contexto quando entrar na tela pela primeira vez
  useEffect(() => {
    console.log('Debug - useEffect triggered:', { hasEmptyFields, theme, clientId, isGenerating, client, hasAutoGenerated });
    if (theme && clientId && client && !isGenerating && !hasAutoGenerated) {
      console.log('Auto-generating context...');
      setHasAutoGenerated(true);
      generateContextWithAI();
    }
  }, [theme, clientId, client, hasAutoGenerated]);

  const fieldConfigs = [
    {
      key: "title" as keyof CreativeContext,
      label: "Título/Headline",
      placeholder: "Ex: Black Friday 2024 - Até 50% OFF",
      icon: FileText,
      description: "Título principal que aparecerá no criativo",
      required: true,
    },
    {
      key: "description" as keyof CreativeContext,
      label: "Descrição da Peça",
      placeholder: "Ex: Criativo promocional para Black Friday destacando descontos em produtos premium",
      icon: FileText,
      description: "Descrição detalhada do que o criativo deve comunicar",
      multiline: true,
      required: true,
    },
    {
      key: "objective" as keyof CreativeContext,
      label: "Objetivo do Criativo",
      placeholder: "Ex: Aumentar vendas durante Black Friday, gerar leads, aumentar awareness",
      icon: Target,
      description: "Qual o objetivo principal desta peça",
      required: true,
    },
    {
      key: "targetAudience" as keyof CreativeContext,
      label: "Público-alvo Específico",
      placeholder: "Ex: Mulheres 25-45 anos, classe B/C, interessadas em moda",
      icon: Users,
      description: "Público específico para este criativo (pode ser diferente do cliente geral)",
      required: false,
    },
    {
      key: "copy" as keyof CreativeContext,
      label: "Copy da Imagem (TEXTO QUE APARECERÁ NA IMAGEM) ⭐",
      placeholder: "Ex: BLACK FRIDAY\\n50% OFF\\nCompre agora!",
      icon: Quote,
      description: "ESTE TEXTO aparecerá EXATAMENTE como escrito na imagem gerada (máximo 3-4 linhas)",
      multiline: true,
      required: true,
    },
    {
      key: "caption" as keyof CreativeContext,
      label: "Legenda Sugerida",
      placeholder: "Ex: 🔥 BLACK FRIDAY chegou! Corre que é só até domingo! #BlackFriday #Promoção",
      icon: MessageSquare,
      description: "Legenda para acompanhar o post nas redes sociais",
      multiline: true,
      required: false,
    },
  ];

  return (
    <div className="space-y-6">
      <div className="flex items-center justify-between">
        <div>
          <h3 className="text-lg font-medium mb-2">Validar Contexto Criativo</h3>
          <p className="text-muted-foreground">
            Revise e aprove o contexto antes de gerar a imagem
          </p>
        </div>
        
        <div className="flex items-center gap-3">
          <Button 
            onClick={generateContextWithAI}
            disabled={isGenerating}
            variant="outline"
            size="sm"
            className="gap-2"
          >
            {isGenerating ? (
              <Loader2 className="w-4 h-4 animate-spin" />
            ) : (
              <Sparkles className="w-4 h-4" />
            )}
            {isGenerating ? "Gerando..." : "Gerar com IA"}
          </Button>
          
          <Badge variant={completionPercentage === 100 ? "default" : "secondary"}>
            {completionPercentage}% completo
          </Badge>
          {completionPercentage === 100 && (
            <CheckCircle className="w-5 h-5 text-green-600" />
          )}
        </div>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        {fieldConfigs.map((field) => {
          const Icon = field.icon;
          const value = context[field.key];
          const isCompleted = value.trim() !== "";
          
          return (
            <Card 
              key={field.key} 
              className={cn(
                "transition-all duration-200",
                isCompleted ? "border-green-200 bg-green-50/50" : "border-border"
              )}
            >
              <CardHeader className="pb-3">
                <div className="flex items-center gap-2">
                  <Icon className={cn(
                    "w-4 h-4",
                    isCompleted ? "text-green-600" : "text-muted-foreground"
                  )} />
                  <CardTitle className="text-sm font-medium">
                    {field.label}
                    {field.required && <span className="text-red-500 ml-1">*</span>}
                  </CardTitle>
                  {isCompleted && (
                    <CheckCircle className="w-4 h-4 text-green-600 ml-auto" />
                  )}
                </div>
                <p className="text-xs text-muted-foreground">
                  {field.description}
                </p>
              </CardHeader>
              
              <CardContent className="pt-0">
                <div className="space-y-2">
                  <Label htmlFor={field.key} className="sr-only">
                    {field.label}
                  </Label>
                  
                  {field.multiline ? (
                    <Textarea
                      id={field.key}
                      placeholder={field.placeholder}
                      value={value}
                      onChange={(e) => onContextUpdate(field.key, e.target.value)}
                      rows={field.key === "copy" ? 4 : 3}
                      className={cn(
                        "resize-none",
                        isCompleted && "border-green-300 focus:border-green-400"
                      )}
                    />
                  ) : (
                    <Input
                      id={field.key}
                      placeholder={field.placeholder}
                      value={value}
                      onChange={(e) => onContextUpdate(field.key, e.target.value)}
                      className={cn(
                        isCompleted && "border-green-300 focus:border-green-400"
                      )}
                    />
                  )}
                  
                  {field.key === "copy" && (
                    <div className="space-y-1">
                      <p className="text-xs text-muted-foreground">
                        💡 Use \\n para quebras de linha. Este texto será usado EXATAMENTE como está na imagem.
                      </p>
                      <p className="text-xs text-orange-600 font-medium">
                        ⚠️ IMPORTANTE: Este texto aparecerá na imagem final sem modificações.
                      </p>
                    </div>
                  )}
                </div>
              </CardContent>
            </Card>
          );
        })}
      </div>

      {completionPercentage > 60 && (
        <Card className="bg-blue-50 border-blue-200">
          <CardContent className="p-4">
            <div className="flex items-start gap-3">
              <CheckCircle className="w-5 h-5 text-blue-600 mt-0.5 flex-shrink-0" />
              <div className="space-y-1">
                <h5 className="font-medium text-blue-900">Contexto quase pronto!</h5>
                <p className="text-sm text-blue-700">
                  {completionPercentage === 100 
                    ? "Todos os campos estão preenchidos. Você pode prosseguir para a geração da imagem."
                    : `Complete os campos obrigatórios restantes para prosseguir.`
                  }
                </p>
              </div>
            </div>
          </CardContent>
        </Card>
      )}

      {completionPercentage < 50 && (
        <Card className="bg-yellow-50 border-yellow-200">
          <CardContent className="p-4">
            <div className="flex items-start gap-3">
              <Target className="w-5 h-5 text-yellow-600 mt-0.5 flex-shrink-0" />
              <div className="space-y-1">
                <h5 className="font-medium text-yellow-900">Mais informações necessárias</h5>
                <p className="text-sm text-yellow-700">
                  Preencha pelo menos os campos obrigatórios (*) para gerar um criativo de qualidade.
                </p>
              </div>
            </div>
          </CardContent>
        </Card>
      )}
    </div>
  );
}

function cn(...classes: (string | boolean | undefined)[]): string {
  return classes.filter(Boolean).join(' ');
}